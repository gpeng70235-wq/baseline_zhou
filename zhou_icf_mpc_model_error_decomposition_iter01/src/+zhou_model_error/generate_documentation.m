function F=freeze_status(project,before)
F=struct('status',"UNAVAILABLE",'before_files',height(before),'after_files',NaN, ...
    'changed_files',NaN,'detail',"No comparable SHA256 snapshots were available.");
after=safe_read(fullfile(project.root,'SOURCE_SHA256_AFTER.csv'));
if isempty(after)&&~isempty(before)
    try
        after=zhou_model_error.snapshot_upstreams(project,"AFTER");
    catch ME
        F.status="HASH_FAILED";F.detail="AFTER snapshot failed: "+string(ME.message);return
    end
end
F.after_files=height(after);if isempty(before)||isempty(after),return,end
kb=before.upstream_project+"|"+before.relative_path;ka=after.upstream_project+"|"+after.relative_path;
[inAfter,locA]=ismember(kb,ka);changed=nnz(~inAfter);matched=find(inAfter);
if ~isempty(matched),changed=changed+nnz(before.sha256(matched)~=after.sha256(locA(matched)));end
changed=changed+nnz(~ismember(ka,kb));F.changed_files=changed;
if changed==0
    F.status="PASS";F.detail="Documentation-time BEFORE/AFTER key and SHA256 comparison found zero added, deleted, or modified upstream files.";
else
    F.status="FAIL";F.detail="Documentation-time comparison found "+changed+" added, deleted, or modified upstream files.";
end
end

