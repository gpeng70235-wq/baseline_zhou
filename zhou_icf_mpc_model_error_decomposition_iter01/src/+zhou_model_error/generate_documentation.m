end

function T=safe_read(path)
if isfile(path)
    % Force CSV delimiter: automatic detection can mistake Windows path
    % backslashes in SOURCE_PROJECTS.csv for delimiters.
    T=readtable(path,'TextType','string','Delimiter',',','VariableNamingRule','preserve');
else
    T=table();
end
end

function v=value_if_present(T,name,default)
name=string(name);
if ismember(name,string(T.Properties.VariableNames)),v=T.(name)(1);else,v=default;end
end

function n=count_equal(T,field,value)
field=string(field);
if isempty(T)||~ismember(field,string(T.Properties.VariableNames)),n=0;else,n=nnz(T.(field)==value);end
end

function n=copy_failures(P)
if isempty(P)||~ismember("byte_identical",string(P.Properties.VariableNames)),n=NaN;else,n=nnz(~logical(P.byte_identical));end
end

function s=rate_for(M,p,field)
q=M.predictor==p;if any(q),s=pct_or_na(M.(field)(find(q,1)));else,s="N/A";end
end

function s=range_text(x)
x=x(isfinite(x));if isempty(x),s="N/A";else,s=num_or_na(min(x))+" .. "+num_or_na(max(x));end
end

function v=weighted(x,w)
keep=isfinite(x)&isfinite(w)&w>0;if any(keep),v=sum(x(keep).*w(keep))/sum(w(keep));else,v=NaN;end
end

function s=num_or_na(x)
if isempty(x)||~isscalar(x)||~isfinite(double(x)),s="N/A";else,s=string(sprintf('%.12g',double(x)));end
end

function s=pct_or_na(x)
if isempty(x)||~isscalar(x)||~isfinite(double(x)),s="N/A";else,s=string(sprintf('%.6f%%',100*double(x)));end
end

function s=signed_pct(x)
if isempty(x)||~isscalar(x)||~isfinite(double(x)),s="N/A";else,s=string(sprintf('%+.6f percentage points',100*double(x)));end
end

function s=logical_text(x)
if logical(x),s="PASS";else,s="FAIL";end
end

function s=esc(x)
s=string(x);s=replace(s,newline," ");s=replace(s,"|","\|");s=replace(s,"`","'");
end

