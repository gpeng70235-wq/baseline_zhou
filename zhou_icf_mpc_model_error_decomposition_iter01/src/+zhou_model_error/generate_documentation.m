    P.false_safe_rate=value_if_present(D,'avg_false_safe_rate',P.false_safe_rate);
    P.top1_flip_rate=value_if_present(D,'top1_avg_plant_flip_rate',P.top1_flip_rate);
end
R=safe_read(fullfile(base,'residual_decomposition.csv'));
if ~isempty(R)
    q=R.case_id=="ALL";
    if any(q)
        P.sequence_ratio=R.sequence_ul_to_total_ratio(find(q,1));
        P.model_ratio=R.model_ul_to_total_ratio(find(q,1));
        P.plant_model_rms_A=R.model_plant_vector_rms_A(find(q,1));
    end
end
Q=safe_read(fullfile(base,'candidate_decision_comparison.csv'));
if ~isempty(Q)
    w=Q.sample_count;P.top1_flip_rate=weighted(Q.avg_plant_top1_flip_rate,w);
    P.mode_flip_rate=weighted(Q.avg_plant_mode_flip_rate,w);
end
end

function T=one_cohort(T,name)
