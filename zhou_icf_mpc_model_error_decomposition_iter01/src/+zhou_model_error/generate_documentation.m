function result=generate_documentation(project,T,S,decision,caseInfo,figureManifest)
%GENERATE_DOCUMENTATION Build the complete, data-backed audit handoff.
% The reports are generated only from the frozen project configuration,
% sample table, registered summary tables, decision table, case registry,
% figure manifest, and provenance CSVs. No controller is changed here.

arguments
    project (1,1) struct
    T table
    S (1,1) struct
    decision table
    caseInfo table
    figureManifest table
end

requiredSummaryFields=["predictor_metrics","contribution","confusion","candidate", ...
    "correlations","spectrum","repeatability","case_classification"];
for name=requiredSummaryFields
    assert(isfield(S,name),'ZhouModelError:DocumentationInput', ...
        'Missing summary table S.%s.',name);
end
assert(height(T)>0&&height(decision)==1&&height(caseInfo)>0, ...
    'ZhouModelError:DocumentationInput','Documentation inputs must be populated.');
assert(all(ismember(project.model_error.predictor_names,string(S.predictor_metrics.predictor))), ...
    'ZhouModelError:DocumentationInput','Predictor metrics do not cover P0--P5.');

C=build_context(project,T,S,decision,caseInfo,figureManifest);
rootFiles=["README.md","HANDOFF.md","CHANGELOG.md","RUN_AND_REPRODUCE.md"];
docFiles=["PROJECT_SCOPE.md","PREVIOUS_WORK_INVENTORY.md","DUPLICATE_WORK_CHECK.md", ...
    "SOURCE_PROJECT_INVENTORY.md","PATH_CONFLICT_REPORT.md","BASELINE_REPRODUCTION_REPORT.md", ...
    "ORIGINAL_PREDICTOR_DEFINITION.md","TIMING_ALIGNMENT_AUDIT.md", ...
    "ORACLE_PREDICTOR_DEFINITION.md","EXPERIMENT_PROTOCOL.md","METRIC_DEFINITIONS.md", ...
    "MODEL_ERROR_DECOMPOSITION_REPORT.md","DECISION_AND_NEXT_STEP.md", ...
    "KNOWN_LIMITATIONS.md","PROTOTYPE_GATE_REPORT.md"];

write_md(fullfile(project.root,'README.md'),readme_document(C));
write_md(fullfile(project.root,'HANDOFF.md'),handoff_document(C));
write_md(fullfile(project.root,'CHANGELOG.md'),changelog_document(C));
write_md(fullfile(project.root,'RUN_AND_REPRODUCE.md'),reproduce_document(C));
write_md(fullfile(project.dirs.docs,'PROJECT_SCOPE.md'),scope_document(C));
write_md(fullfile(project.dirs.docs,'PREVIOUS_WORK_INVENTORY.md'),previous_document(C));
write_md(fullfile(project.dirs.docs,'DUPLICATE_WORK_CHECK.md'),duplicate_document(C));
write_md(fullfile(project.dirs.docs,'SOURCE_PROJECT_INVENTORY.md'),source_document(C));
write_md(fullfile(project.dirs.docs,'ORIGINAL_PREDICTOR_DEFINITION.md'),original_document(C));
write_md(fullfile(project.dirs.docs,'TIMING_ALIGNMENT_AUDIT.md'),timing_document(C));
write_md(fullfile(project.dirs.docs,'ORACLE_PREDICTOR_DEFINITION.md'),oracle_document(C));
write_md(fullfile(project.dirs.docs,'EXPERIMENT_PROTOCOL.md'),protocol_document(C));
write_md(fullfile(project.dirs.docs,'METRIC_DEFINITIONS.md'),metrics_document(C));
write_md(fullfile(project.dirs.docs,'MODEL_ERROR_DECOMPOSITION_REPORT.md'),report_document(C));
write_md(fullfile(project.dirs.docs,'DECISION_AND_NEXT_STEP.md'),decision_document(C));
write_md(fullfile(project.dirs.docs,'KNOWN_LIMITATIONS.md'),limitations_document(C));
ensure_supporting_documents(C);

rootPaths=fullfile(project.root,rootFiles);docPaths=fullfile(project.dirs.docs,docFiles);
allPaths=[rootPaths,docPaths];
assert(all(isfile(allPaths)),'ZhouModelError:DocumentationMissing', ...
    'One or more registered handoff documents were not generated.');
result=struct('generated',true,'file_count',numel(allPaths), ...
    'root_documents',rootPaths,'docs_documents',docPaths, ...
    'case_count',C.case_count,'sample_count',C.sample_count, ...
    'decision_code',C.decision.decision_code(1), ...
    'upstream_changed_files_at_documentation',C.freeze.changed_files, ...
    'upstream_validation_status',C.freeze.status);
end

function C=build_context(project,T,S,decision,caseInfo,figureManifest)
C=struct();C.project=project;C.T=T;C.S=S;C.decision=decision;C.caseInfo=caseInfo;
C.figureManifest=figureManifest;C.generated_at=string(datetime('now','TimeZone','Asia/Shanghai', ...
    'Format','yyyy-MM-dd HH:mm:ss XXX'));
C.case_count=numel(unique(T.case_id,'stable'));C.sample_count=height(T);
C.common_sample_count=nnz(T.oracle_previous_valid);C.predictors=project.model_error.predictor_names;
C.metrics_all=one_cohort(S.predictor_metrics,"REPRODUCTION_ALL");
C.metrics_primary=one_cohort(S.predictor_metrics,"ENGINEERING_PRIMARY");
C.contribution_all=one_cohort(S.contribution,"REPRODUCTION_ALL");
C.contribution_primary=one_cohort(S.contribution,"ENGINEERING_PRIMARY");
C.confusion_primary=one_cohort(S.confusion,"ENGINEERING_PRIMARY");
C.candidate_primary=one_cohort(S.candidate,"ENGINEERING_PRIMARY");
C.baseline=safe_read(fullfile(project.dirs.summary,'baseline_comparison.csv'));
C.upstreams=safe_read(fullfile(project.root,'SOURCE_PROJECTS.csv'));
C.before=safe_read(fullfile(project.root,'SOURCE_SHA256_BEFORE.csv'));
C.provenance=safe_read(fullfile(project.root,'COPIED_FILE_PROVENANCE.csv'));
C.freeze=freeze_status(project,C.before);
C.prior=prior_sequence_evidence(project);
C.matlab_release=matlab_release();
C.raw_csv=fullfile(project.dirs.raw,'model_error_samples.csv');
C.summary_root=project.dirs.summary;C.figure_root=project.dirs.figures;
C.baseline_passed=sum(logical(C.baseline.pass));C.baseline_failed=height(C.baseline)-C.baseline_passed;
C.figure_count=sum(logical(figureManifest.generated));
C.figure_failed=height(figureManifest)-C.figure_count;
end

