function pass = experiment_P1_saliency_probe(cfg, run_id)
%EXPERIMENT_P1_SALIENCY_PROBE Verify an observed, not merely configured, effect.
cfg.motor.Ld = cfg.experiments.P1.Ld;
cfg.motor.Lq = cfg.experiments.P1.Lq;
cfg.id_ref = cfg.experiments.P1.id;
[metrics,trace] = zhou_ipmsm.run_probe_case(cfg);

degenerate_cfg = cfg;
degenerate_L = mean([cfg.motor.Ld cfg.motor.Lq]);
degenerate_cfg.motor.Ld = degenerate_L;
degenerate_cfg.motor.Lq = degenerate_L;
degenerate_metrics = zhou_ipmsm.run_probe_case(degenerate_cfg);
metrics.saliency_metric_delta = norm([metrics.rmse_d_A-degenerate_metrics.rmse_d_A, ...
    metrics.rmse_q_A-degenerate_metrics.rmse_q_A, ...
    metrics.mean_torque_Nm-degenerate_metrics.mean_torque_Nm]);
pass = common_acceptance(metrics,cfg.acceptance) && ...
    metrics.saliency_metric_delta>=cfg.acceptance.min_saliency_effect;
zhou_ipmsm.io.save_experiment_result(cfg,run_id,'saliency',metrics,trace,pass);
end

function pass = common_acceptance(metrics,thresholds)
pass = metrics.illegal_commands<=thresholds.max_illegal && ...
    metrics.negative_durations==0 && ...
    metrics.constraint_d_violations<=thresholds.max_constraint_violations && ...
    metrics.constraint_q_violations<=thresholds.max_constraint_violations && ...
    metrics.geometry_reference_outside<=thresholds.max_geometry_outside && ...
    metrics.saturated_commands<=thresholds.max_saturated_commands && ...
    max([metrics.rmse_d_A metrics.rmse_q_A])<=thresholds.max_rmse_A && ...
    metrics.phase_a_thd<=thresholds.max_phase_a_thd;
end
