function matrix = experiment_matrix(base)
%EXPERIMENT_MATRIX Pre-registered operating conditions; no per-case tuning.

arguments
    base struct = base_parameters()
end

speeds = [100 100 300 300 500 500];
currents = [base.low_current_A base.high_current_A ...
    base.low_current_A base.high_current_A ...
    base.low_current_A base.high_current_A];
loads = ["low" "high" "low" "high" "low" "high"];
matrix = repmat(common_scenario(base),1,numel(speeds));
for k = 1:numel(speeds)
    matrix(k).name = sprintf('%drpm_%s_%gA',speeds(k),loads(k),currents(k));
    matrix(k).speed_rpm = speeds(k);
    matrix(k).iq_ref_A = currents(k);
    matrix(k).current_level = loads(k);
end
end

function scenario = common_scenario(base)
scenario = struct('name','', 'speed_rpm',100, 'current_level',"low", ...
    'load_torque_Nm',0, 'theta0_rad',0.17, 'id0_A',0, 'iq0_A',0, ...
    'id_ref_A',0, 'iq_ref_A',base.low_current_A, ...
    'reference_ramp_s',base.reference_ramp_s, ...
    'reference_profile',"ramp", ...
    'simulation_time_s',base.simulation_time_s, ...
    'steady_window_start_s',base.steady_window_start_s, ...
    'Jd_limit_A2',base.Jd_limit_A2, 'Jq_limit_A2',base.Jq_limit_A2, ...
    'alpha_mode',"axis_specific", 'F_estimator',"algebraic_iter11", ...
    'eso_pole',NaN, 'integration_step_s',base.default_integration_step_s, ...
    'plant_Ld_scale',1, 'plant_Lq_scale',1, 'plant_Rs_scale',1, ...
    'plant_psi_f_scale',1, 'motor_model',"P1");
end
